/** Look up projects by slug, in the order given (throws on a typo so it's caught at build). */
export function pickProjects(...slugs: string[]): Project[] {
  return slugs.map((slug) => {
    const project = projects.find((p) => p.slug === slug);
    if (!project) throw new Error(`Unknown project slug: ${slug}`);
    return project;
  });
}
